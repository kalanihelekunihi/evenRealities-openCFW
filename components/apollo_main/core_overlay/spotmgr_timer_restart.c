typedef __UINTPTR_TYPE__ open_cfw_spotmgr_timer_restart_uintptr;

#define OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS 0x400083E0U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_COMPARE0_ADDRESS 0x400083E8U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_INTCLR_ADDRESS 0x40008068U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_NVIC_ICPR_ADDRESS 0xE000E288U

#define OPEN_CFW_SPOTMGR_TIMER_RESTART_TICKS_PER_MICROSECOND 6U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_ENABLE_MASK 0x00000001U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_CLEAR_MASK 0x00000002U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_COMPARE_BOTH_MASK 0xC0000000U
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_NVIC_MASK 0x00040000U

#ifndef OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32(address) \
    (*(const volatile unsigned int *)( \
        open_cfw_spotmgr_timer_restart_uintptr)(address))
#endif

#ifndef OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32
#define OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(address, value) \
    (*(volatile unsigned int *)( \
        open_cfw_spotmgr_timer_restart_uintptr)(address) = (value))
#endif

/*
 * ABI-compatible source replacement for AmbiqSuite's public
 * am_hal_spotmgr_timer_restart at 0x0048028A...0x004802CD.
 */
__attribute__((used, noinline))
void open_cfw_spotmgr_timer_restart(unsigned int delay_microseconds)
{
    unsigned int value;

    value = OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS
    );
    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS,
        value & ~OPEN_CFW_SPOTMGR_TIMER_RESTART_ENABLE_MASK
    );

    value = OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS
    );
    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS,
        value | OPEN_CFW_SPOTMGR_TIMER_RESTART_CLEAR_MASK
    );
    value = OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS
    );
    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS,
        value & ~OPEN_CFW_SPOTMGR_TIMER_RESTART_CLEAR_MASK
    );

    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_COMPARE0_ADDRESS,
        delay_microseconds *
            OPEN_CFW_SPOTMGR_TIMER_RESTART_TICKS_PER_MICROSECOND
    );
    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_INTCLR_ADDRESS,
        OPEN_CFW_SPOTMGR_TIMER_RESTART_COMPARE_BOTH_MASK
    );
    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_NVIC_ICPR_ADDRESS,
        OPEN_CFW_SPOTMGR_TIMER_RESTART_NVIC_MASK
    );

    value = OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS
    );
    OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32(
        OPEN_CFW_SPOTMGR_TIMER_RESTART_CTRL0_ADDRESS,
        value | OPEN_CFW_SPOTMGR_TIMER_RESTART_ENABLE_MASK
    );
}

#undef OPEN_CFW_SPOTMGR_TIMER_RESTART_WRITE32
#undef OPEN_CFW_SPOTMGR_TIMER_RESTART_READ32
