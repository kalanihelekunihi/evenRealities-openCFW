    def test_routed_source_helpers_match_expected_stock_bytes(self) -> None:
        self.assertEqual(self.report["schema_version"], 2)
        self.assertEqual(self.report["toolchain_profile"], "apple-clang")
        self.assertEqual(self.report["target"], "thumbv7em-none-eabi")
        self.assertEqual(self.report["helper_count"], 32)
        self.assertEqual(self.report["routed_helper_count"], 32)
        self.assertEqual(self.report["source_owned_helper_bytes"], 10110)
        self.assertTrue(self.report["all_helpers_match_expected"])
        self.assertTrue(self.report["all_helpers_routed"])

