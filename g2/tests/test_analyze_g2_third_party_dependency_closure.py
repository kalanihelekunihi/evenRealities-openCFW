def load_analyzer():
    spec = importlib.util.spec_from_file_location("analyze_g2_third_party_dependency_closure", ANALYZER)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class ThirdPartyDependencyClosureTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.analyzer = load_analyzer()

    def test_manifest_is_closed_and_evidenced(self):
        data = json.loads(self.analyzer.MANIFEST.read_text())
        rows = data["dependencies"]
        self.assertEqual({row["family"] for row in rows}, self.analyzer.EXPECTED_FAMILIES)
        self.assertTrue(all(row["functional_status"] in self.analyzer.ALLOWED_STATUS for row in rows))
        for row in rows:
            self.assertTrue(row["evidence"])
            self.assertTrue(all((ROOT / path).is_file() for path in row["evidence"]))

    def test_open_status_is_rejected_by_contract(self):
        self.assertNotIn("open_local_gap", self.analyzer.ALLOWED_STATUS)

