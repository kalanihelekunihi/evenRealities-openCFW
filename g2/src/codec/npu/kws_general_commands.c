static void put16(uint8_t *out, uint16_t value)
{
    out[0] = (uint8_t)value;
    out[1] = (uint8_t)(value >> 8);
}

static void put32(uint8_t *out, uint32_t value)
{
    put16(out, (uint16_t)value);
    put16(out + 2, (uint16_t)(value >> 16));
}

static uint32_t address_word(struct g2_address address)
{
    return ((uint32_t)address.slot << 28) | address.offset;
}

int g2_kws_emit_general_command(unsigned ordinal, uint8_t *out,
                                size_t capacity, unsigned *program_index,
                                size_t *written)
{
    const struct g2_general_spec *spec;
    uint8_t *body;
    size_t length;
    uint32_t header, control, extents;
    unsigned i;
    if (ordinal >= G2_KWS_GENERAL_COMMAND_COUNT || out == 0)
        return -1;
    spec = &general[ordinal];
    length = spec->link_slot == 255 ? 44u : 48u;
    if (capacity < length)
        return -1;
    for (i = 0; i < length; ++i)
        out[i] = 0;
    header = UINT32_C(1) | spec->header_flags;
    if (spec->link_slot == 255) {
        header |= UINT32_C(1) << 17;
        body = out + 4;
    } else {
        put32(out + 4, ((uint32_t)spec->link_slot << 28) | spec->link_offset);
        body = out + 8;
    }
    put32(out, header);
    put32(body, address_word(spec->source_a));
    put32(body + 4, address_word(spec->source_b));
    put32(body + 12, address_word(spec->destination));
    control = spec->kind;
    if (spec->kind == G2_TENSOR_VECTOR)
        control |= (uint32_t)spec->arithmetic << 9;
    else if (spec->kind == G2_TENSOR_TENSOR)
        control |= (uint32_t)spec->arithmetic << 11;
    put32(body + 16, control);
    extents = ((uint32_t)spec->extent.outer << 20) |
              ((uint32_t)spec->extent.middle << 8) | spec->extent.inner;
    put32(body + 20, extents);
    put16(body + 24, spec->source_stride.middle);
    put16(body + 26, spec->source_stride.outer);
    put16(body + 28, spec->destination_stride.middle);
    put16(body + 30, spec->destination_stride.outer);
    if (program_index != 0)
        *program_index = spec->program_index;
    if (written != 0)
        *written = length;
    return 0;
}
