/* ---- hal_i2c.c ---------------------------------------------------------- */

typedef struct {
    uint32_t scl;     /* +0x0 */
    uint32_t sda;     /* +0x4 */
    uint32_t scl_cfg; /* +0x8 am_hal_gpio_pincfg_t */
    uint32_t sda_cfg; /* +0xc */
} g2_i2c_pins_data_t;

/* am_hal_iom_config_t in the stock one-byte-enum layout (20 bytes). */
typedef struct {
    uint8_t interface_mode; /* +0x00 1 = I2C */
    uint8_t pad01[3];
    uint32_t clock_hz;      /* +0x04 */
    uint8_t spi_mode;       /* +0x08 */
    uint8_t pad09[3];
    uint32_t *nb_txn_buf;   /* +0x0c */
    uint32_t nb_txn_len;    /* +0x10 words */
} g2_iom_config_data_t;
_Static_assert(sizeof(g2_iom_config_data_t) == 20u, "am_hal_iom_config_t");

typedef struct {
    uint32_t module;                /* +0x0 IOM module */
    void *handle;                   /* +0x4 filled by am_hal_iom_initialize */
    const g2_i2c_pins_data_t *pins; /* +0x8 */
    const void *config;             /* +0xc */
} g2_i2c_bus_data_t;
_Static_assert(sizeof(g2_i2c_bus_data_t) == 16u, "bus row");

