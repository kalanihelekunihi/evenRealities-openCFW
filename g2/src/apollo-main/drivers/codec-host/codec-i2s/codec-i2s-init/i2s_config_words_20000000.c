/* I2S configuration and DMA descriptor initialized from the official
 * Apollo Main low-RAM record. The config's +0x24 word changes at runtime. */
#include <stdint.h>

__attribute__((section(".data.opencfw.codec.i2s_config_base"), aligned(4), used))
uint8_t g2_codec_i2s_config_base[40] = {
    0x00, 0x00, 0x00, 0x00, 0x0b, 0x02, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x28, 0x07, 0x00, 0x20,
    0xf0, 0x3f, 0x07, 0x20, 0x00, 0x00, 0x00, 0x00
};

__attribute__((section(".data.opencfw.codec.i2s_dma_descriptor"), aligned(4), used))
uint8_t g2_codec_i2s_dma_descriptor[24] = {
    0x18, 0x4e, 0x36, 0x20, 0x98, 0x5a, 0x36, 0x20,
    0x20, 0x03, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00
};

_Static_assert(sizeof(g2_codec_i2s_config_base) == 40, "I2S config selected access extent");
_Static_assert(sizeof(g2_codec_i2s_dma_descriptor) == 24, "I2S DMA descriptor extent");
