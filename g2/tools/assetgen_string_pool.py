#!/usr/bin/env python3
"""Generate a packed string-pool C source file from a source string list.

XC-005 host tooling: an Apollo string-pool data region (UI text, log format
strings, protocol constant names, ...) should be reconstructed as a
documented, editable *list of strings* plus this generator, not as an opaque
byte array lifted from the stock image. The list lives in a small JSON file
next to the consuming component (an AD-* item's job to place and license);
this tool turns it into a single concatenated, NUL-terminated byte blob with
either an offset table or a pointer table, matching whichever physical
layout the retained caller code is shown (by the AD-* item's own analysis)
to expect.

Input JSON schema
------------------
{
  "pool_name": "example_strings",
  "encoding": "utf-8",          // optional, defaults to utf-8
  "entries": [
    {"name": "GREETING", "text": "Hello"},
    {"name": "FAREWELL", "text": "Goodbye"}
  ]
}

`name` becomes an index constant (`<POOL>_<NAME>`); entry order is preserved
and is the index order. Output is deterministic: byte-identical for the same
input, so `git diff` on the generated file reviews the same thing as `git
diff` on the JSON.

This tool is openCFW-authored and offered under the repository's MIT License
(see CONTRIBUTING.md).
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


class StringPoolError(Exception):
    pass


def _c_identifier(text: str) -> str:
    ident = re.sub(r"[^A-Za-z0-9_]", "_", text).upper()
    if not ident or ident[0].isdigit():
        ident = "_" + ident
    return ident


def load_spec(path: Path) -> dict:
    spec = json.loads(path.read_text())
    if "pool_name" not in spec or "entries" not in spec:
        raise StringPoolError("spec must have 'pool_name' and 'entries'")
    if not isinstance(spec["entries"], list) or not spec["entries"]:
        raise StringPoolError("'entries' must be a non-empty list")
    names = [e["name"] for e in spec["entries"]]
    if len(names) != len(set(names)):
        raise StringPoolError("entry names must be unique")
    return spec


def pack(spec: dict):
    """Return (blob_bytes, offsets, names) for the given spec."""
    encoding = spec.get("encoding", "utf-8")
    blob = bytearray()
    offsets = []
    names = []
    for entry in spec["entries"]:
        offsets.append(len(blob))
        blob += entry["text"].encode(encoding) + b"\x00"
        names.append(entry["name"])
    return bytes(blob), offsets, names


def decode(blob: bytes, offsets: list, encoding: str = "utf-8") -> list:
    """Independent reference decoder: split the blob back into strings using
    only the offsets, mirroring what consuming C code would do."""
    out = []
    for offset in offsets:
        end = blob.index(b"\x00", offset)
        out.append(blob[offset:end].decode(encoding))
    return out


def generate_c_source(spec: dict, blob: bytes, offsets: list, names: list,
                       layout: str, source_path: str, tool_version: str) -> str:
    pool = spec["pool_name"]
    pool_upper = _c_identifier(pool)
    lines = []
    lines.append("/* SPDX-License-Identifier: MIT")
    lines.append(" * Generated by g2/tools/assetgen_string_pool.py (openCFW asset generator tool, XC-005).")
    lines.append(f" * Generator version: {tool_version}")
    lines.append(f" * Source spec: {source_path}")
    lines.append(f" * {len(names)} entries, {len(blob)} data bytes, layout={layout}")
    lines.append(" * Re-running the generator against the same spec reproduces this file")
    lines.append(" * byte-for-byte.")
    lines.append(" */")
    lines.append("#include <stddef.h>")
    lines.append("")
    lines.append("enum {")
    for index, name in enumerate(names):
        lines.append(f"    {pool_upper}_{_c_identifier(name)} = {index},")
    lines.append(f"    {pool_upper}_COUNT = {len(names)}")
    lines.append("};")
    lines.append("")
    escaped = "".join(f"\\x{b:02x}" for b in blob)
    lines.append(f"static const char {pool}_bytes[{len(blob)}] = \"{escaped}\";")
    lines.append("")
    if layout in ("offsets", "both"):
        lines.append(f"const unsigned int {pool}_offsets[{len(offsets)}] = {{")
        lines.append("    " + ", ".join(str(o) for o in offsets) + ",")
        lines.append("};")
        lines.append("")
    if layout in ("pointers", "both"):
        lines.append(f"const char *const {pool}_ptrs[{len(offsets)}] = {{")
        for o in offsets:
            lines.append(f"    {pool}_bytes + {o},")
        lines.append("};")
        lines.append("")
    return "\n".join(lines)


def build(spec_path: Path, layout: str = "offsets", tool_version: str = "1"):
    spec = load_spec(spec_path)
    blob, offsets, names = pack(spec)
    decoded = decode(blob, offsets, spec.get("encoding", "utf-8"))
    expected = [e["text"] for e in spec["entries"]]
    if decoded != expected:
        raise StringPoolError("round-trip mismatch: packed blob does not decode back to the source strings")
    text = generate_c_source(spec, blob, offsets, names, layout, str(spec_path), tool_version)
    return text, {"entries": len(names), "data_bytes": len(blob), "pool_name": spec["pool_name"]}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("spec", type=Path, help="source string-pool JSON spec")
    parser.add_argument("--layout", choices=("offsets", "pointers", "both"), default="offsets")
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args(argv)
    try:
        text, meta = build(args.spec, args.layout)
    except StringPoolError as exc:
        print(f"assetgen_string_pool: {exc}", file=sys.stderr)
        return 1
    args.output.write_text(text)
    print(f"wrote {args.output} ({meta['entries']} entries, {meta['data_bytes']} data bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
