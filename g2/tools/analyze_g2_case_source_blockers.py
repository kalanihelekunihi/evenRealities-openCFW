#!/usr/bin/env python3
"""Summarize case component source-completion blockers."""

from __future__ import annotations

import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import analyze_g2_completion_readiness as readiness


OUT = ROOT / "tools/manifests/g2-case-source-blockers.json"
CASE_FINAL = ROOT / "tools/manifests/g2-case-final-classification-summary.json"
CASE_SOURCE_IMAGE = ROOT / "tools/manifests/g2-case-source-image-summary.json"
SOURCE_ONLY_MANIFEST = ROOT / "manifests/g2-2.2.6.10-source-only.json"


def _read(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _source_only_macos_route() -> dict:
    manifest = _read(SOURCE_ONLY_MANIFEST)
    source_image = _read(CASE_SOURCE_IMAGE)
    override = manifest["component_overrides"]["case"]
    provider = override["provider"]
    artifacts = source_image["artifacts"]
    if provider["kind"] != "source_build":
        raise RuntimeError("case source-only provider is not source_build")
    if provider["sha256"] != artifacts["even_sha256"]:
        raise RuntimeError("case source-only provider digest disagrees")
    if provider["size"] != source_image["metrics"]["even_package_bytes"]:
        raise RuntimeError("case source-only provider size disagrees")
    return {
        "manifest": "manifests/g2-2.2.6.10-source-only.json",
        "provider_path": provider["path"],
        "provider_kind": provider["kind"],
        "provider_size": provider["size"],
        "provider_sha256": provider["sha256"],
        "toolchain_profile": "apple-clang",
        "software_link_complete": source_image["software_link_complete"],
        "software_package_complete": source_image["software_package_complete"],
        "source_translation_units": source_image["metrics"][
            "source_translation_units"],
        "undefined_symbols": source_image["metrics"]["undefined_symbols"],
        "production_routed": source_image["production_routed"],
        "hardware_validation": source_image["hardware_validation"],
    }


def analyze() -> dict:
    component = readiness.analyze()["components"]["case"]
    details = component["details"]
    final = _read(CASE_FINAL)
    metrics = final["metrics"]
    whole_blob = metrics["whole_blob_bucket_bytes"]
    if whole_blob["project_source_candidate"] != component["buckets"][
        "candidate_source_not_routed"]:
        raise RuntimeError("case candidate-source bytes disagree")
    if whole_blob["typed_external_or_unsupported"] != component["buckets"][
        "typed_retained_or_external"]:
        raise RuntimeError("case typed external bytes disagree")
    if whole_blob["generated_transport_fill"] != component["buckets"][
        "generated_or_reconstructible"]:
        raise RuntimeError("case generated bytes disagree")
    return {
        "schema_version": 1,
        "component": "case",
        "size": component["size"],
        "release_blocking_bytes": component["release_blocking_bytes"],
        "production_routed": component["production_routed"],
        "source_complete": component["source_complete"],
        "buckets": component["buckets"],
        "candidate_admission_blocker_class": details[
            "candidate_admission_blocker_class"],
        "candidate_admission_hardware_validation": details[
            "candidate_admission_hardware_validation"],
        "candidate_source_functions": details["candidate_source_functions"],
        "remaining_callable_software_functions": details[
            "remaining_callable_software_functions"],
        "source_image_translation_units": details[
            "source_image_translation_units"],
        "source_image_undefined_symbols": details[
            "source_image_undefined_symbols"],
        "software_image_link_complete": details["software_image_link_complete"],
        "software_even_package_complete": details[
            "software_even_package_complete"],
        "physical_board_services_routed": details[
            "physical_board_services_routed"],
        "open_semantic_questions": details["open_semantic_questions"],
        "ownership_categories": details["ownership_categories"],
        "byte_accounting_metrics": details["byte_accounting_metrics"],
        "byte_accounting_buckets": details["byte_accounting_buckets"],
        "candidate_source_breakdown": metrics["candidate_source_breakdown"],
        "gap_classification_counts": metrics["gap_classification_counts"],
        "physical_bucket_digest": metrics["physical_bucket_digest"],
        "whole_blob_bucket_bytes": whole_blob,
        "source_image_board_contract": details["source_image_board_contract"],
        "source_only_macos_route": _source_only_macos_route(),
    }


def main() -> int:
    report = analyze()
    OUT.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps({
        "release_blocking_bytes": report["release_blocking_bytes"],
        "production_routed": report["production_routed"],
        "candidate_admission_blocker_class": report[
            "candidate_admission_blocker_class"],
        "candidate_source_functions": report["candidate_source_functions"],
        "remaining_callable_software_functions": report[
            "remaining_callable_software_functions"],
        "buckets": report["buckets"],
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
