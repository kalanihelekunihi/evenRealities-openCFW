"""Experimental admission of recovered platform getter and generated dispatch table."""
import json,re,shutil
from verify_gx8002_platform_read_system import verify as compare
from verify_gx8002_logging import check_paths
from analyze_gx8002_upstream_objects import ROOT,IMAGE,sha
from build_transparent_image import Elf32

def verify(prefix=None,sdk=None,output=None):
    check_paths(prefix,sdk);evidence=compare();candidate=json.loads((ROOT/'docs/research/gx8002-platform-read-candidate.json').read_text())
    path=ROOT/'build/gx8002-board/platform-read.elf';elf=Elf32(path.read_bytes(),str(path))
    expected={'.text.platform_read':(0x16824,188),'.rodata.platform_read':(0x169e0,40)}
    rows=[];stock=IMAGE.read_bytes()
    for section in elf.sections:
        if not section['flags']&2 or not section['size']:continue
        name=section['name']
        if name not in expected:raise ValueError('Unexpected allocation')
        offset,size=expected[name];data=elf.contents(section)
        if section['address']!=offset+0x1000dfec or len(data)>size or elf.relocations(section['index']):raise ValueError('Placement')
        symbol='open_cfw_gx8002_platform_read'+('' if name=='.text.platform_read' else '_'+name.split('.')[-1])
        rows.append({'symbol':symbol,'section_name':name,'ownership_kind':'compiled_c' if name=='.text.platform_read' else 'generated_source_data','compiled_bytes':len(data),'compiled_sha256':sha(data),'stock_occurrences':[{'symbol':symbol,'package_offset':offset,'bytes':size,'sha256':sha(stock[offset:offset+size]),'region':'image_a_sram'}]})
    if len(rows)!=2 or any(s['name'] and s['section']==0 for s in elf.symbols()):raise ValueError('Missing/unresolved section')
    registry=(ROOT/'tools/build_gx8002_source_candidate.py').read_text()
    for name in set(re.findall(r"'(gx8002-[^']+\.json)'",registry)):
        if name=='gx8002-platform-read-source-verification.json':continue
        p=ROOT/'docs/research'/name
        if not p.exists():continue
        r=json.loads(p.read_text())
        for row in r.get('functions',[r]):
            for occurrence in row.get('stock_occurrences',row.get('exact_stock_occurrences',[])):
                start=occurrence.get('package_offset');size=occurrence.get('bytes')
                if start is not None and size is not None and any(start<o+n and o<start+size for o,n in expected.values()):raise ValueError(('Ownership overlap',name))
    if output:
        output.mkdir(parents=True,exist_ok=True);shutil.copyfile(path,output/'platform-read.elf')
    table=next(section for section in elf.sections if section['name']=='.rodata.platform_read')
    import struct
    targets=struct.unpack('<10I',elf.contents(table))
    if any(not 0x10024810<=target<0x100248cc or target%2 for target in targets):raise ValueError('Getter dispatch target outside code')
    files=sorted({p.name for p in (ROOT/'tools').glob('*gx8002_platform_read*.py')}|{'execute_gx8002_system_getter.py','gx8002_lvp_system_oracle.py','verify_gx8002_memcpy_source.py'})
    return {'functions':rows,'evidence':evidence,'evidence_sha256':{n:sha((ROOT/'tools'/n).read_bytes()) for n in files},'source_admitted':True,'hardware_qualified':False,'limits':evidence['limits']+['Narrow stores and one mask use visible C-SKY inline assembly within C; dispatch table generated by compiler/linker.']+['Experimental hybrid admission only; complete source-only firmware unfinished.']}

if __name__=='__main__':
    r=verify();(ROOT/'docs/research/gx8002-platform-read-source-verification.json').write_text(json.dumps(r,indent=2)+'\n');print('platform getter experimental admission checks passed')
