#!/usr/bin/env python3
"""Summarize touch component source-completion blockers."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import analyze_g2_completion_readiness as readiness


OUT = ROOT / "tools/manifests/g2-touch-source-blockers.json"
TOUCH_FINAL = ROOT / "tools/manifests/g2-touch-final-classification-summary.json"
TOUCH_PHYSICAL_BUCKETS = (
    ROOT / "tools/manifests/g2-touch-final-physical-byte-buckets.tsv"
)
TOUCH_SOURCE_IMAGE = ROOT / "tools/manifests/g2-touch-source-image-summary.json"
SOURCE_ONLY_MANIFEST = ROOT / "manifests/g2-2.2.6.10-source-only.json"


def _read(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _source_only_macos_route() -> dict:
    manifest = _read(SOURCE_ONLY_MANIFEST)
    source_image = _read(TOUCH_SOURCE_IMAGE)
    override = manifest["component_overrides"]["touch"]
    provider = override["provider"]
    artifacts = source_image["artifacts"]
    if provider["kind"] != "source_build":
        raise RuntimeError("touch source-only provider is not source_build")
    if provider["sha256"] != artifacts["fwpk_sha256"]:
        raise RuntimeError("touch source-only provider digest disagrees")
    if provider["size"] != source_image["metrics"]["fwpk_bytes"]:
        raise RuntimeError("touch source-only provider size disagrees")
    return {
        "manifest": "manifests/g2-2.2.6.10-source-only.json",
        "provider_path": provider["path"],
        "provider_kind": provider["kind"],
        "provider_size": provider["size"],
        "provider_sha256": provider["sha256"],
        "toolchain_profile": "apple-clang",
        "software_link_complete": source_image["software_link_complete"],
        "software_package_complete": source_image["software_package_complete"],
        "source_translation_units": source_image["metrics"][
            "source_translation_units"],
        "undefined_symbols": source_image["metrics"]["undefined_symbols"],
        "production_routed": source_image["production_routed"],
        "hardware_validation": source_image["hardware_validation"],
    }


def _physical_bucket_rows() -> list[dict]:
    rows = []
    with TOUCH_PHYSICAL_BUCKETS.open(encoding="utf-8", newline="") as handle:
        filtered = (
            line for line in handle
            if not line.startswith("#") and line.strip()
        )
        for row in csv.DictReader(filtered, delimiter="\t"):
            rows.append({
                "category": row["category"],
                "bytes": int(row["bytes"]),
                "address_set_sha256": row["address_set_sha256"],
                "content_sha256": row["content_sha256"],
                "owner_or_category": row["owner_or_category"],
                "license_status": row["license_status"],
                "unresolved_sub_boundary": row["unresolved_sub_boundary"],
                "evidence": row["evidence"],
            })
    return rows


def analyze() -> dict:
    component = readiness.analyze()["components"]["touch"]
    details = component["details"]
    final = _read(TOUCH_FINAL)
    metrics = final["metrics"]
    rows = _physical_bucket_rows()
    row_bytes = {row["category"]: row["bytes"] for row in rows}
    whole_blob = metrics["whole_blob_bucket_bytes"]
    if whole_blob["project_source_candidate"] != component["buckets"][
        "candidate_source_not_routed"]:
        raise RuntimeError("touch candidate-source bytes disagree")
    if whole_blob["typed_external_or_unsupported"] != component["buckets"][
        "typed_retained_or_external"]:
        raise RuntimeError("touch typed external bytes disagree")
    if whole_blob["generated_transport_fill"] != component["buckets"][
        "generated_or_reconstructible"]:
        raise RuntimeError("touch generated bytes disagree")
    typed_rows = {
        name: value for name, value in row_bytes.items()
        if name.startswith("typed_")
    }
    if sum(typed_rows.values()) != component["buckets"]["typed_retained_or_external"]:
        raise RuntimeError("touch typed physical buckets do not conserve")
    return {
        "schema_version": 1,
        "component": "touch",
        "size": component["size"],
        "release_blocking_bytes": component["release_blocking_bytes"],
        "production_routed": component["production_routed"],
        "source_complete": component["source_complete"],
        "buckets": component["buckets"],
        "candidate_admission_blocker_class": details[
            "candidate_admission_blocker_class"],
        "candidate_admission_hardware_validation": details[
            "candidate_admission_hardware_validation"],
        "resident_abi_available": details["resident_abi_available"],
        "physical_board_services_routed": details[
            "physical_board_services_routed"],
        "candidate_source_functions": details["candidate_source_functions"],
        "remaining_callable_software_functions": details[
            "remaining_callable_software_functions"],
        "remaining_source_or_implementation_functions": details[
            "remaining_source_or_implementation_functions"],
        "unimplemented_application_contracts": details[
            "unimplemented_application_contracts"],
        "source_image_translation_units": details[
            "source_image_translation_units"],
        "source_image_undefined_symbols": details[
            "source_image_undefined_symbols"],
        "software_image_link_complete": details["software_image_link_complete"],
        "software_fwpk_package_complete": details[
            "software_fwpk_package_complete"],
        "candidate_provenance": details["candidate_provenance"],
        "typed_code_complement_bytes": details["typed_code_complement_bytes"],
        "typed_noncode_bytes": details["typed_noncode_bytes"],
        "typed_noncode_partition": details["typed_noncode_partition"],
        "whole_blob_bucket_bytes": whole_blob,
        "physical_bucket_digest": metrics["physical_bucket_digest"],
        "physical_bucket_rows": rows,
        "typed_physical_bucket_bytes": typed_rows,
        "candidate_union_address_set_sha256": metrics[
            "candidate_union_address_set_sha256"],
        "candidate_union_content_sha256": metrics[
            "candidate_union_content_sha256"],
        "generation_receipt_sha256": details["generation_receipt"][
            "generation_receipt_sha256"],
        "source_only_macos_route": _source_only_macos_route(),
    }


def main() -> int:
    report = analyze()
    OUT.write_text(json.dumps(report, indent=2, sort_keys=True) + "\n")
    print(json.dumps({
        "release_blocking_bytes": report["release_blocking_bytes"],
        "production_routed": report["production_routed"],
        "candidate_admission_blocker_class": report[
            "candidate_admission_blocker_class"],
        "resident_abi_available": report["resident_abi_available"],
        "candidate_source_functions": report["candidate_source_functions"],
        "buckets": report["buckets"],
    }, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
