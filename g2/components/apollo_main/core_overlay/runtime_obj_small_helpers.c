/*
 * Source-shaped recovery of LVGL 9.3 `update_obj_state` at
 * 0x0043EBEC..0x0043EE2C.  The stock literal loads intentionally keep their
 * original PC-relative form because their literals live in the adjacent
 * retained assert-string island; calls are named relocations.
 */
__attribute__((used, naked))
void open_cfw_runtime_update_obj_state_exact(void *obj, unsigned int new_state)
{
    __asm__ volatile(
        "push.w {r0, r1, r4, r5, r6, r7, r8, sb, sl, fp, lr}\n"
        "sub sp, #0x1c\n"
        "ldr r0, [sp, #0x1c]\n"
        "ldrh r0, [r0, #0x28]\n"
        "ldrh.w r1, [sp, #0x20]\n"
        "cmp r0, r1\n"
        "beq.w L_update_done\n"
        "ldr r0, [sp, #0x1c]\n"
        "cmp r0, #0\n"
        "bne.n L_update_obj_nonnull\n"
        "ldr r0, [pc, #0x238]\n"
        "str r0, [sp, #8]\n"
        "ldr r0, [pc, #0x238]\n"
        "str r0, [sp, #4]\n"
        "ldr r0, [pc, #0x238]\n"
        "str r0, [sp]\n"
        "ldr r3, [pc, #0x238]\n"
        "movw r2, #0x38f\n"
        "ldr r1, [pc, #0x234]\n"
        "movs r0, #3\n"
        "bl open_cfw_retained_assert_log\n"
        "L_update_null_trap:\n"
        "movs r0, #0\n"
        "movs.w r1, #-1\n"
        "str r0, [r1]\n"
        "b.n L_update_null_trap\n"
        "L_update_obj_nonnull:\n"
        "ldr r0, [sp, #0x1c]\n"
        "ldrh r0, [r0, #0x28]\n"
        "strh.w r0, [sp, #8]\n"
        "ldrh.w r2, [sp, #0x20]\n"
        "ldrh.w r1, [sp, #8]\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_style_state_cmp\n"
        "strb.w r0, [sp, #4]\n"
        "ldrb.w r0, [sp, #4]\n"
        "cmp r0, #0\n"
        "bne.n L_update_visible_diff\n"
        "ldrh.w r0, [sp, #0x20]\n"
        "ldr r1, [sp, #0x1c]\n"
        "strh r0, [r1, #0x28]\n"
        "b.n L_update_done\n"
        "L_update_visible_diff:\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_obj_state_pre_hook\n"
        "ldrh.w r0, [sp, #0x20]\n"
        "ldr r1, [sp, #0x1c]\n"
        "strh r0, [r1, #0x28]\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_obj_state_post_hook\n"
        "mov.w r0, #0x280\n"
        "bl open_cfw_retained_lv_malloc_zeroed\n"
        "movs r4, r0\n"
        "movs r5, #0\n"
        "movs r0, #0\n"
        "str r0, [sp]\n"
        "b.n L_style_guard\n"
        "L_next_style:\n"
        "ldr r0, [sp]\n"
        "adds r0, r0, #1\n"
        "str r0, [sp]\n"
        "L_style_guard:\n"
        "ldr r0, [sp]\n"
        "ldr r1, [sp, #0x1c]\n"
        "ldrh r1, [r1, #0x2a]\n"
        "ubfx r1, r1, #4, #6\n"
        "uxth r1, r1\n"
        "cmp r0, r1\n"
        "bhs.w L_start_transitions\n"
        "cmp r5, #0x20\n"
        "bhs.w L_start_transitions\n"
        "ldr r0, [sp, #0x1c]\n"
        "ldr r0, [r0, #0xc]\n"
        "ldr r1, [sp]\n"
        "add.w r0, r0, r1, lsl #3\n"
        "str r0, [sp, #0xc]\n"
        "ldr r0, [sp, #0x1c]\n"
        "ldr r0, [r0, #0xc]\n"
        "ldr r1, [sp]\n"
        "add.w r0, r0, r1, lsl #3\n"
        "ldr r0, [r0, #4]\n"
        "bic r0, r0, #0xff000000\n"
        "bl open_cfw_retained_selector_state\n"
        "strh.w r0, [sp, #6]\n"
        "ldr r0, [sp, #0x1c]\n"
        "ldr r0, [r0, #0xc]\n"
        "ldr r1, [sp]\n"
        "add.w r0, r0, r1, lsl #3\n"
        "ldr r0, [r0, #4]\n"
        "bic r0, r0, #0xff000000\n"
        "bl open_cfw_retained_selector_part\n"
        "str r0, [sp, #0x14]\n"
        "ldrh.w r0, [sp, #6]\n"
        "ldrh.w r1, [sp, #0x20]\n"
        "mvns r1, r1\n"
        "tst r0, r1\n"
        "bne.n L_next_style\n"
        "ldr r0, [sp, #0xc]\n"
        "ldr r0, [r0, #4]\n"
        "ubfx r0, r0, #0x19, #1\n"
        "cmp r0, #0\n"
        "bne.n L_next_style\n"
        "add r2, sp, #0x10\n"
        "movs r1, #0x68\n"
        "ldr r0, [sp, #0xc]\n"
        "ldr r0, [r0]\n"
        "bl open_cfw_retained_style_get_transition_prop\n"
        "cmp r0, #1\n"
        "bne.n L_next_style\n"
        "ldr r6, [sp, #0x10]\n"
        "movs r7, #0\n"
        "b.n L_prop_guard\n"
        "L_next_candidate_scan:\n"
        "adds.w r8, r8, #1\n"
        "L_candidate_scan_compare:\n"
        "cmp r8, r5\n"
        "bhs.n L_candidate_add\n"
        "movs.w sb, #0x14\n"
        "mul r0, sb, r8\n"
        "add r0, r4\n"
        "ldr.w fp, [r0, #4]\n"
        "mov r0, fp\n"
        "bl open_cfw_retained_selector_state\n"
        "mov sl, r0\n"
        "mov r0, fp\n"
        "bl open_cfw_retained_selector_part\n"
        "mul sb, sb, r8\n"
        "add.w r1, r4, sb\n"
        "ldrb r1, [r1, #8]\n"
        "ldr r2, [r6]\n"
        "ldrb r2, [r2, r7]\n"
        "cmp r1, r2\n"
        "bne.n L_next_candidate_scan\n"
        "ldr r1, [sp, #0x14]\n"
        "cmp r0, r1\n"
        "bne.n L_next_candidate_scan\n"
        "ldrh.w r0, [sp, #6]\n"
        "uxth.w sl, sl\n"
        "cmp sl, r0\n"
        "blo.n L_next_candidate_scan\n"
        "L_candidate_add:\n"
        "cmp r8, r5\n"
        "bne.n L_advance_property\n"
        "movs r0, #0x14\n"
        "ldr r1, [r6, #0xc]\n"
        "mul r2, r0, r5\n"
        "strh r1, [r4, r2]\n"
        "ldr r1, [r6, #0x10]\n"
        "mul r2, r0, r5\n"
        "add r2, r4\n"
        "strh r1, [r2, #2]\n"
        "ldr r1, [r6, #8]\n"
        "mul r2, r0, r5\n"
        "add r2, r4\n"
        "str r1, [r2, #0xc]\n"
        "ldr r1, [r6]\n"
        "ldrb r1, [r1, r7]\n"
        "mul r2, r0, r5\n"
        "add r2, r4\n"
        "strb r1, [r2, #8]\n"
        "ldr r1, [r6, #4]\n"
        "mul r2, r0, r5\n"
        "add r2, r4\n"
        "str r1, [r2, #0x10]\n"
        "ldr r1, [sp, #0xc]\n"
        "ldr r1, [r1, #4]\n"
        "bic r1, r1, #0xff000000\n"
        "mul r0, r0, r5\n"
        "add r0, r4\n"
        "str r1, [r0, #4]\n"
        "adds r5, r5, #1\n"
        "L_advance_property:\n"
        "adds r7, r7, #1\n"
        "L_prop_guard:\n"
        "ldr r0, [r6]\n"
        "ldrb r0, [r0, r7]\n"
        "cmp r0, #0\n"
        "beq.w L_next_style\n"
        "cmp r5, #0x20\n"
        "bhs.w L_next_style\n"
        "movs.w r8, #0\n"
        "b.n L_candidate_scan_compare\n"
        "L_start_transitions:\n"
        "movs r6, #0\n"
        "b.n L_transition_guard\n"
        "L_transition_loop:\n"
        "movs r7, #0x14\n"
        "mul r0, r7, r6\n"
        "add r0, r4\n"
        "ldr r0, [r0, #4]\n"
        "bl open_cfw_retained_selector_part\n"
        "mul r7, r7, r6\n"
        "add.w r1, r4, r7\n"
        "str r1, [sp]\n"
        "ldrh.w r3, [sp, #0x20]\n"
        "ldrh.w r2, [sp, #8]\n"
        "movs r1, r0\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_start_transition\n"
        "adds r6, r6, #1\n"
        "L_transition_guard:\n"
        "cmp r6, r5\n"
        "blo.n L_transition_loop\n"
        "movs r0, r4\n"
        "bl open_cfw_retained_lv_free\n"
        "ldrb.w r0, [sp, #4]\n"
        "cmp r0, #1\n"
        "bne.n L_check_layout_refresh\n"
        "movs r2, #0xff\n"
        "movs.w r1, #0xf0000\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_refresh_ext_draw\n"
        "b.n L_update_done\n"
        "L_check_layout_refresh:\n"
        "ldrb.w r0, [sp, #4]\n"
        "cmp r0, #3\n"
        "bne.n L_check_draw_pad_refresh\n"
        "movs r2, #0xff\n"
        "movs.w r1, #0xf0000\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_refresh_ext_draw\n"
        "b.n L_update_done\n"
        "L_check_draw_pad_refresh:\n"
        "ldrb.w r0, [sp, #4]\n"
        "cmp r0, #2\n"
        "bne.n L_update_done\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_obj_state_pre_hook\n"
        "ldr r0, [sp, #0x1c]\n"
        "bl open_cfw_retained_layout_refresh\n"
        "L_update_done:\n"
        "add sp, #0x24\n"
        "pop.w {r4, r5, r6, r7, r8, sb, sl, fp, pc}\n"
    );
}
