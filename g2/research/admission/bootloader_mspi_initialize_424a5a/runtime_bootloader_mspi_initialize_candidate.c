static uint32_t load32(const uint8_t *p)
{
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8U) |
           ((uint32_t)p[2] << 16U) | ((uint32_t)p[3] << 24U);
}

static void store32(uint8_t *p, uint32_t value)
{
    p[0] = (uint8_t)value;
    p[1] = (uint8_t)(value >> 8U);
    p[2] = (uint8_t)(value >> 16U);
    p[3] = (uint8_t)(value >> 24U);
}

uint32_t open_cfw_bootloader_mspi_initialize_424a5a(
    uint32_t module, void **handle,
    uint8_t states[OPEN_CFW_MSPI_MODULE_COUNT][OPEN_CFW_MSPI_STATE_BYTES])
{
    uint8_t *state;
    uint32_t prefix;

    if (module >= OPEN_CFW_MSPI_MODULE_COUNT) return OPEN_CFW_MSPI_STATUS_OUT_OF_RANGE;
    if (handle == 0) return OPEN_CFW_MSPI_STATUS_INVALID_ARG;
    state = states[module];
    prefix = load32(state);
    if ((prefix & 0x01000000U) != 0U) return OPEN_CFW_MSPI_STATUS_INVALID_OPERATION;

    store32(state, ((prefix | 0x01000000U) & 0xFF000000U) | 0x00BEBEBEU);
    store32(state + 4U, module);
    state[0x0CU] = 0U;
    store32(state + 0x18U, 0U);
    state[0x8C9U] = 7U;
    store32(state + 0x8CCU, 8U);
    *handle = state;
    return OPEN_CFW_MSPI_STATUS_SUCCESS;
}
