static uint32_t load32(const uint8_t *p)
{
    return (uint32_t)p[0] | ((uint32_t)p[1] << 8U) |
           ((uint32_t)p[2] << 16U) | ((uint32_t)p[3] << 24U);
}

static void store32(uint8_t *p, uint32_t value)
{
    p[0]=(uint8_t)value; p[1]=(uint8_t)(value>>8U);
    p[2]=(uint8_t)(value>>16U); p[3]=(uint8_t)(value>>24U);
}

uint32_t open_cfw_bootloader_mspi_configure_424af0(
    uint8_t *handle, const open_cfw_mspi_config *config,
    uint8_t states[OPEN_CFW_MSPI_CONFIG_MODULES][OPEN_CFW_MSPI_CONFIG_STATE_BYTES],
    open_cfw_mspi_registers registers[OPEN_CFW_MSPI_CONFIG_MODULES])
{
    uint32_t prefix, module, maximum;
    uint8_t *state;
    if (handle == 0) return 2U;
    prefix = load32(handle);
    if ((prefix & 0x01FFFFFFU) != 0x01BEBEBEU) return 2U;
    if ((prefix & 0x02000000U) != 0U) return 7U;
    module = load32(handle + 4U);
    state = states[module];
    registers[module].dev0xip &= ~1U;
    registers[module].dev0scrambling = 0U;
    registers[module].dev0axi = 0U;
    store32(state + 0x18U, config->tcb_address);
    store32(state + 0x14U, config->tcb_size_words);
    if (config->tcb_address != 0U) {
        uint32_t end = config->tcb_address + config->tcb_size_words * 4U;
        state[0x8C8U] = end < 0x20080000U ? 1U : 0U;
        maximum = ((config->tcb_size_words - 8U) * 4U) / 72U;
        if (maximum > 256U) maximum = 256U;
        store32(state + 0x858U, maximum);
    }
    state[9U] = config->clock_on_d4;
    state[8U] = 1U;
    state[10U] = 26U;
    return 0U;
}
