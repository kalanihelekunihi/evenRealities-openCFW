#!/usr/bin/env python3
"""Generate the stock fault lookup's 256 wrapping rows from pinned payload bytes."""
import hashlib
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
G2 = ROOT / "g2"
PAYLOAD = G2 / "blobs/official/g2-2.2.6.10/ota_s200_firmware_ota.bin"
SOURCE = G2 / "components/audio/uart_thread_source_candidate/fault_lookup_overrun_509b48.c"
PIN = "19044a72bdfeb04c6b1b104d87da7b98e13cc18928528d84d999b6bcc0ba9701"
BASE = 0x438000
TABLE = 0x6c8e60


def main():
    blob = PAYLOAD.read_bytes()[32:]
    if hashlib.sha256(blob).hexdigest() != PIN:
        raise RuntimeError("Apollo payload changed")
    rows = [struct.unpack_from("<HHI", blob, TABLE-BASE+8*i) for i in range(256)]
    lines = [
        "/* Generated by generate_fault_lookup_overrun_509b48_20261016.py.",
        " * Rows 43..255 overlap unrelated stock data. Raw pointers there retain",
        " * stock addresses; whole-image relocation and validity remain open. */",
        "#include <stdint.h>",
        "struct audio_fault_code_row { uint16_t code, reserved; const char *message; };",
        "extern const struct audio_fault_code_row audio_fault_code_table[43];",
        "struct fault_overrun_row { uint16_t code, reserved; uint32_t pointer; };",
        "_Static_assert(sizeof(struct fault_overrun_row)==8u, \"fault row ABI\");",
        "static const struct fault_overrun_row stock_overrun_rows[213] = {",
    ]
    for code, reserved, pointer in rows[43:]:
        lines.append(f"    {{0x{code:04x}u, 0x{reserved:04x}u, 0x{pointer:08x}u}},")
    lines += [
        "};",
        "const char *audio_fault_unmapped_code_message_509b48(uint16_t code) {",
        "    uint8_t index = 0u;",
        "    for (;;) {",
        "        if (index < 43u) {",
        "            if (audio_fault_code_table[index].code == code)",
        "                return audio_fault_code_table[index].message;",
        "        } else {",
        "            const struct fault_overrun_row *row = &stock_overrun_rows[index-43u];",
        "            if (row->code == code)",
        "                return (const char *)(uintptr_t)row->pointer;",
        "        }",
        "        index = (uint8_t)(index + 1u);",
        "    }",
        "}",
    ]
    SOURCE.write_text("\n".join(lines) + "\n")
    print(SOURCE.relative_to(ROOT), hashlib.sha256(SOURCE.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
